"""Bundle the admin service into one file you can paste into Cloudflare.

usage: python3 tools/bundle_admin.py
Reads admin/src/worker.js, app.html, app.css and app.js and writes admin/worker.js.
"""
import json
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "admin" / "src"
html = (SRC / "app.html").read_text(encoding="utf-8")
html = html.replace("/*__APP_CSS__*/", (SRC / "app.css").read_text(encoding="utf-8"))
html = html.replace("/*__APP_JS__*/", (SRC / "app.js").read_text(encoding="utf-8"))
if "</script" in (SRC / "app.js").read_text(encoding="utf-8"):
    raise SystemExit("app.js must not contain </script")
worker = (SRC / "worker.js").read_text(encoding="utf-8")
out = "// GENERATED by tools/bundle_admin.py from admin/src. Edit those files, not this one.\n" + \
      worker.replace("__APP_HTML__", json.dumps(html, ensure_ascii=False))
(SRC.parent / "worker.js").write_text(out, encoding="utf-8")
print(f"admin/worker.js written ({len(out) // 1024} KB)")
